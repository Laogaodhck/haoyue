using System.Text.Json.Nodes;
using Haoyue.Runtime.Configuration;
using Haoyue.Runtime.Secrets;

namespace Haoyue.Tests;

[Collection(ProcessEnvironmentCollection.Name)]
public sealed class ConfigTests : IDisposable
{
    private readonly string _dir = Path.Combine(Path.GetTempPath(), "haoyue-tests", Guid.NewGuid().ToString("N"));

    public ConfigTests() => Directory.CreateDirectory(_dir);

    public void Dispose()
    {
        try { Directory.Delete(_dir, recursive: true); } catch (IOException) { }
    }

    private ConfigStore NewStore() => new(
        Path.Combine(_dir, "config.json"),
        Path.Combine(_dir, "state.json"));

    [Fact]
    public void MissingConfig_CreatesDefaults_AndPersists()
    {
        var store = NewStore();
        Assert.True(File.Exists(Path.Combine(_dir, "config.json")));

        // First-run seed is generated by serializing the code-defined defaults.
        // Providers and model routing are intentionally empty so users must create their own.
        Assert.Empty(store.Config.Providers);
        Assert.Empty(store.Config.Routing.Fallback);
        Assert.Equal(40, store.Config.Agent.MaxSteps);
        Assert.True(store.Config.Routing.FailoverEnabled); // failover default on
        Assert.False(store.Config.Routing.DeepSeekOptimizationEnabled); // DeepSeek optimization default off
        // 本地模型启动预热默认开启：首条消息免等权重加载（实测 -39% 首字延迟），
        // 关闭它必须是用户显式选择，而不是首次安装的默认姿势。
        Assert.True(store.Config.Agent.LocalModelPreload);
    }

    [Fact]
    public void SaveAndReload_RoundTripsProvidersAndModel()
    {
        var store = NewStore();
        store.Config.Providers.Add(new ProviderConfig
        {
            Id = "test",
            Kind = "openai",
            BaseUrl = "https://example.test/v1",
            ApiKey = "config-secret",
            Models = [new ModelConfig { Id = "m1", Alias = "one", ContextWindow = 9000, InputPricePerMTok = 1.5m }],
        });
        store.Config.Provider = "test";
        store.Config.Model = "m1";
        store.Config.Temperature = 0.3;
        store.Save();

        var reloaded = NewStore();
        var provider = Assert.Single(reloaded.Config.Providers, p => p.Id == "test");
        Assert.Equal("test", provider.Id);
        // 重载触发密钥迁移：磁盘值已改为 secret: 引用，使用方视角（ResolveApiKey）仍还原明文。
        Assert.Equal("config-secret", provider.ResolveApiKey());
        Assert.Equal(9000, provider.Models[0].ContextWindow);
        Assert.Equal("one", provider.Models[0].Alias);
        Assert.Equal(1.5m, provider.Models[0].InputPricePerMTok);
        Assert.Equal("test", reloaded.Config.Provider);
        Assert.Equal("m1", reloaded.Config.Model);
        Assert.Equal(0.3, reloaded.Config.Temperature);
    }

    [Fact]
    public void Routing_FailoverEnabled_RoundTrips()
    {
        var store = NewStore();
        store.Config.Routing.FailoverEnabled = false;
        store.Save();

        var reloaded = NewStore();
        Assert.False(reloaded.Config.Routing.FailoverEnabled);
    }

    [Fact]
    public void Save_PreservesUnchangedFieldsWrittenConcurrentlyByAnotherProcess()
    {
        // Simulates CLI (storeA) and daemon (storeB) editing different fields of the
        // shared config.json: the last saver must not clobber the other writer's field.
        var storeA = NewStore();
        var storeB = NewStore();
        storeA.Config.Model = "model-a";
        storeA.Save();

        storeB.Reload(); // baseline = disk content written by A
        storeB.Config.Agent.MaxSteps = 77;
        storeB.Save();

        storeA.Save(); // A changed nothing locally → B's MaxSteps must survive

        var verifier = NewStore();
        Assert.Equal("model-a", verifier.Config.Model);
        Assert.Equal(77, verifier.Config.Agent.MaxSteps);
    }

    [Fact]
    public void Save_MergesDifferentSubFieldsOfSameSection()
    {
        var storeA = NewStore();
        var storeB = NewStore();
        storeA.Config.Agent.Mode = "auto";
        storeA.Save();

        storeB.Reload(); // baseline = disk written by A
        storeB.Config.Agent.MaxSteps = 77; // same section, different leaf
        storeB.Save();

        storeA.Save(); // A changed nothing new → B's MaxSteps must survive the section

        var verifier = NewStore();
        Assert.Equal("auto", verifier.Config.Agent.Mode);
        Assert.Equal(77, verifier.Config.Agent.MaxSteps);
    }

    [Fact]
    public void Save_LocallyChangedFields_WinOverConcurrentWriter()
    {
        var storeA = NewStore();
        var storeB = NewStore();
        storeB.Config.Model = "model-b";
        storeB.Save();

        storeA.Reload(); // A sees model-b as its baseline
        storeA.Config.Model = "model-a2"; // A changed the same field → A wins
        storeA.Config.Agent.MaxSteps = 55;
        storeA.Save();

        var verifier = NewStore();
        Assert.Equal("model-a2", verifier.Config.Model);
        Assert.Equal(55, verifier.Config.Agent.MaxSteps);
    }

    [Fact]
    public void Save_LeavesNoTempFileResidue()
    {
        var store = NewStore();
        store.Config.Model = "x";
        store.Save();
        store.SaveState();

        Assert.Empty(Directory.GetFiles(_dir, "*.tmp", SearchOption.TopDirectoryOnly));
    }

    [Fact]
    public void Routing_DeepSeekOptimization_RoundTrips()
    {
        var store = NewStore();
        store.Config.Routing.DeepSeekOptimizationEnabled = true;
        store.Save();

        var reloaded = NewStore();
        Assert.True(reloaded.Config.Routing.DeepSeekOptimizationEnabled);
    }

    [Fact]
    public void Load_MigratesPlaintextApiKey_ToSecretReference()
    {
        // 模拟旧版配置文件：Provider ApiKey 以明文落盘。加载时必须迁移为 secret: 引用，
        // 磁盘上不再出现明文；ResolveApiKey（请求发送视角）仍能取回明文。
        var configFile = Path.Combine(_dir, "config.json");
        File.WriteAllText(configFile, """
        {
            "schemaVersion": 1,
            "providers": [
                { "id": "p1", "kind": "openai", "baseUrl": "https://example.test/v1", "apiKey": "sk-plaintext-key" }
            ],
            "provider": "p1",
            "model": "m1"
        }
        """);

        var store = NewStore();
        var provider = Assert.Single(store.Config.Providers);
        Assert.Equal("sk-plaintext-key", provider.ResolveApiKey());

        // 每个平台都要迁移：macOS 曾因为 Encrypt 原样返回明文而被当成「无需迁移」。
        Assert.StartsWith(SecretResolver.Prefix, provider.ApiKey);
        Assert.DoesNotContain("sk-plaintext-key", File.ReadAllText(configFile));
        Assert.Empty(store.SecretWarnings);

        // 已迁移的配置再次加载是幂等的（不再触发写盘），密钥仍可解析。
        var reloaded = NewStore();
        Assert.Equal("sk-plaintext-key", reloaded.Config.Providers.Single().ResolveApiKey());
        Assert.Empty(reloaded.SecretWarnings);
    }

    [Fact]
    public void Load_MigratesApiKey_AndSchemaVersion_InOnePass()
    {
        // 旧文件同时缺 schemaVersion 与带明文 Key：|| 的短路求值曾让密钥迁移整个跳过，
        // 只剩 schema 迁移落盘。两者必须都生效。
        var configFile = Path.Combine(_dir, "config.json");
        File.WriteAllText(configFile, """
        {
            "providers": [
                { "id": "p1", "kind": "openai", "baseUrl": "https://example.test/v1", "apiKey": "sk-both-plain" }
            ],
            "provider": "p1",
            "model": "m1"
        }
        """);

        var store = NewStore();

        Assert.Equal(ConfigSchema.CurrentVersion, store.Config.SchemaVersion);
        Assert.StartsWith(SecretResolver.Prefix, store.Config.Providers.Single().ApiKey);
        Assert.DoesNotContain("sk-both-plain", File.ReadAllText(configFile));
        Assert.Equal("sk-both-plain", store.Config.Providers.Single().ResolveApiKey());
    }

    [Fact]
    public void ResolveApiKey_ResolvesSecretReference_AndPassesThroughPlaintext()
    {
        var provider = new ProviderConfig { Id = "p", ApiKey = "legacy-plain" };
        Assert.Equal("legacy-plain", provider.ResolveApiKey());

        provider.ApiKey = SecretResolver.Encrypt("provider/p", "sk-live");
        Assert.StartsWith(SecretResolver.Prefix, provider.ApiKey);
        Assert.Equal("sk-live", provider.ResolveApiKey());
    }

    [Fact]
    public void Reset_RestoresFactoryDefaults_AndPersists()
    {
        var store = NewStore();
        store.Config.Providers.Add(new ProviderConfig
        {
            Id = "custom",
            Kind = "openai",
            BaseUrl = "https://custom.example/v1",
            ApiKey = "reset-me",
        });
        store.Config.Routing.FailoverEnabled = false;
        store.State.DisabledSkills["custom-skill"] = "";
        store.Save();
        store.SaveState();

        store.Reset();

        Assert.DoesNotContain(store.Config.Providers, provider => provider.Id == "custom");
        Assert.Empty(store.Config.Providers);
        Assert.Empty(store.Config.Routing.Fallback);
        Assert.True(store.Config.Routing.FailoverEnabled);
        Assert.Empty(store.State.DisabledSkills);

        var reloaded = NewStore();
        Assert.True(reloaded.Config.Routing.FailoverEnabled);
        Assert.Empty(reloaded.State.DisabledSkills);
    }

    [Fact]
    public void CorruptConfig_FallsBackToDefaults_SetsAnomaly_AndCreatesBackup()
    {
        var configFile = Path.Combine(_dir, "config.json");
        File.WriteAllText(configFile, "{ not json !!");
        var store = NewStore();
        Assert.Equal(40, store.Config.Agent.MaxSteps);
        Assert.True(store.HasAnomaly);
        Assert.NotNull(store.AnomalyDetail);
        Assert.NotNull(store.BackupConfigFile);
        Assert.True(File.Exists(store.BackupConfigFile));
        Assert.Equal("{ not json !!", File.ReadAllText(store.BackupConfigFile));
        Assert.Equal("{ not json !!", File.ReadAllText(configFile));

        store.Reset();
        Assert.False(store.HasAnomaly);
        Assert.Null(store.AnomalyDetail);
        Assert.Null(store.BackupConfigFile);
    }

    [Fact]
    public void MigrateLegacyProfiles_ExtractsDefaultProfileToTopLevel()
    {
        var legacyJson = """
